class Common(unittest.TestCase):
    def test_camel_case(self):
        self.assertEqual(c.lower_camel("transport.play"), "transportPlay")
        self.assertEqual(c.lower_camel("return-to-zero"), "returnToZero")
        self.assertEqual(c.lower_camel("glyph-05"), "glyph05")
        self.assertEqual(c.lower_camel("classic-light"), "classicLight")
        self.assertEqual(c.upper_camel("iconStroke"), "IconStroke")

    def test_keywords_are_back_quoted(self):
        self.assertEqual(c.identifier("import"), "`import`")
        self.assertEqual(c.identifier("play"), "play")
        with self.assertRaises(ValueError):
            c.identifier("9lives")

    def test_numbers_are_short_and_stable(self):
        self.assertEqual([c.number(v) for v in (1.0, 0.123456, -0.00001, 12.5, 2.0000001)],
                         ["1", "0.1235", "0", "12.5", "2"])

    def test_string_literal_escapes(self):
        self.assertEqual(c.string_literal('a "b" \\'), '"a \\"b\\" \\\\"')

    def test_license_comment(self):
        self.assertEqual(c.license_comment("A\n\nB\n"), "// A\n//\n// B\n")


def with_brand(data=None):
    """minimal() plus a constant brand group and a second theme."""
    d = data or minimal()
    d["tokens"]["brand"] = {"kind": "color", "constant": True,
                            "items": {"gold": "Brand gold", "cyanInk": "Brand deep cyan"}}
    d["themes"][0]["values"]["brand"] = {"gold": "#EFC031", "cyanInk": "#0077A8"}
    second = copy.deepcopy(d["themes"][0])
    second["id"] = "night-shift"
    second["appearance"] = "dark"
    second["placeholder"] = True
    d["themes"].append(second)
    return d


class TokensSwift(unittest.TestCase):
    def setUp(self):
        self.files = g.generate(minimal())
        self.theme = self.files["Sources/SymbioticTokens/Generated/Theme+Generated.swift"]

    def test_file_set(self):
        self.assertEqual(sorted(self.files), ["Sources/SymbioticTokens/Generated/SystemColorName+Generated.swift",
                                              "Sources/SymbioticTokens/Generated/Theme+Generated.swift"])

    def test_header_and_groups(self):
        self.assertTrue(self.theme.startswith("// Generated by tools/generate.py"))
        self.assertIn("    public let text: TextColors", self.theme)
        self.assertIn("    public let type: TypeStyles", self.theme)
        self.assertIn("        /// Main text\n        public let primary: ThemeColor", self.theme)
        self.assertIn("    public struct SpacingMetrics: Sendable, Hashable {", self.theme)

    def test_values(self):
        self.assertIn("primary: ThemeColor(hex: 0x000000FF)", self.theme)
        self.assertIn("window: ThemeColor(system: .windowBackgroundColor, fallback: 0xFFFFFFFF, appearance: .light)",
                      self.theme)
        self.assertIn("m: 12", self.theme)
        self.assertIn("body: TypeStyle(size: 13, weight: .regular)", self.theme)
        self.assertIn("    public static let classicLight = Theme(", self.theme)
        self.assertIn("    public static let all: [Theme] = [.classicLight]", self.theme)

    def test_alpha_hex(self):
        self.assertEqual(g.hex_literal("#00000080"), "0x00000080")
        self.assertEqual(g.hex_literal("#abcdef"), "0xABCDEFFF")

    def test_system_colour_enum_lists_every_allowed_name(self):
        text = self.files["Sources/SymbioticTokens/Generated/SystemColorName+Generated.swift"]
        for name in ("windowBackgroundColor", "controlAccentColor", "systemRed"):
            self.assertIn(f"    case {name}\n", text)
            self.assertIn(f"        case .{name}: return .{name}\n", text)

    def test_output_is_deterministic(self):
        self.assertEqual(g.generate(minimal()), self.files)

    def test_theme_and_groups_have_public_memberwise_initialisers(self):
        self.assertIn("    public init(\n"
                      "        id: String,\n"
                      "        appearance: ThemeAppearance,\n"
                      "        isPlaceholder: Bool = false,\n"
                      "        text: TextColors,\n"
                      "        surface: SurfaceColors,\n"
                      "        spacing: SpacingMetrics,\n"
                      "        type: TypeStyles\n"
                      "    ) {\n"
                      "        self.id = id\n", self.theme)
        self.assertIn("        self.type = type\n", self.theme)
        self.assertIn("        public init(\n"
                      "            primary: ThemeColor\n"
                      "        ) {\n"
                      "            self.primary = primary\n"
                      "        }\n", self.theme)
        self.assertIn("        public init(\n            m: CGFloat\n        ) {\n", self.theme)

    def test_keyword_names_are_back_quoted_in_initialisers(self):
        d = minimal()
        d["tokens"]["spacing"]["items"]["default"] = "Default gap"
        d["themes"][0]["values"]["spacing"]["default"] = 4
        text = g.generate(d)[f"{g.OUT}/Theme+Generated.swift"]
        self.assertIn("            `default`: CGFloat\n", text)
        self.assertIn("            self.`default` = `default`\n", text)

    def test_every_theme_is_listed_in_order(self):
        text = g.generate(with_brand())[f"{g.OUT}/Theme+Generated.swift"]
        self.assertIn("    public static let all: [Theme] = [.classicLight, .nightShift]", text)
        self.assertIn("    public static let nightShift = Theme(\n"
                      "        id: \"night-shift\",\n"
                      "        appearance: .dark,\n"
                      "        isPlaceholder: true,", text)

    def test_constant_group_is_a_theme_group_and_a_namespace(self):
        text = g.generate(with_brand())[f"{g.OUT}/Theme+Generated.swift"]
        self.assertIn("    public let brand: BrandColors", text)
        self.assertIn("/// Theme-independent tokens: the same in every theme (tokens.json group `brand`).\n"
                      "public enum Brand {\n"
                      "    /// Brand gold\n"
                      "    public static let gold: ThemeColor = ThemeColor(hex: 0xEFC031FF)\n"
                      "    /// Brand deep cyan\n"
                      "    public static let cyanInk: ThemeColor = ThemeColor(hex: 0x0077A8FF)\n"
                      "}\n", text)
        # Every theme refers to the one namespace value.
        self.assertEqual(text.count("            gold: Brand.gold"), 2)
        self.assertNotIn("public enum Text", text)

    def test_constant_group_cannot_hold_a_system_colour(self):
        d = with_brand()
        for theme in d["themes"]:
            theme["values"]["brand"]["gold"] = {"system": "systemYellow", "fallback": "#EFC031"}
        with self.assertRaises(tokenlib.TokenError) as ctx:
            g.generate(d)
        self.assertEqual(ctx.exception.problems,
                         ["brand.gold: brand is constant, so it needs a fixed colour, not a system colour"])

    def test_theme_init_pins_colour_groups_to_the_theme_appearance(self):
        """Review M3: the Theme's appearance, not each colour's, decides how system colours resolve."""
        self.assertIn("        self.text = text.pinned(to: appearance)\n", self.theme)
        self.assertIn("        self.surface = surface.pinned(to: appearance)\n", self.theme)
        self.assertIn("        self.spacing = spacing\n", self.theme)
        self.assertIn("        /// The same colours, with every system colour resolved in `appearance`.\n"
                      "        public func pinned(to appearance: ThemeAppearance) -> TextColors {\n"
                      "            TextColors(\n"
                      "                primary: self.primary.pinned(to: appearance)\n"
                      "            )\n"
                      "        }\n", self.theme)
        self.assertNotIn("-> SpacingMetrics {", self.theme)

    def problems(self, data):
        with self.assertRaises(tokenlib.TokenError) as ctx:
            g.generate(data)
        return ctx.exception.problems

    def test_constant_namespace_must_not_clash_with_a_swift_name(self):
        """Review M4."""
        for group, swift in (("theme", "Theme"), ("themeColor", "ThemeColor"), ("color", "Color"),
                             ("symbioticTokens", "SymbioticTokens")):
            d = minimal()
            d["tokens"][group] = {"kind": "points", "constant": True, "items": {"x": "X"}}
            d["themes"][0]["values"][group] = {"x": 1}
            self.assertEqual(self.problems(d), [
                f"{group}: a constant group becomes the top-level Swift name {swift}, which is already "
                "used; rename the group"])

    def test_group_names_must_not_clash_with_theme_properties(self):
        for group in ("id", "appearance", "isPlaceholder", "all", "named", "standard"):
            d = minimal()
            d["tokens"][group] = {"kind": "points", "items": {"x": "X"}}
            d["themes"][0]["values"][group] = {"x": 1}
            self.assertEqual(self.problems(d), [
                f"{group}: the group name clashes with Theme.{group}; rename the group"])

    def test_theme_ids_must_not_clash_with_theme_members(self):
        d = minimal()
        d["themes"][0]["id"] = "text"
        self.assertEqual(self.problems(d), [
            "theme text: its Swift name Theme.text clashes with another Theme member; rename the theme"])


if __name__ == "__main__":
    unittest.main()
