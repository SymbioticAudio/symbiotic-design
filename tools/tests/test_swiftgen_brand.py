import pathlib
import sys
import unittest

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import swiftgen_brand as g  # noqa: E402
import swiftgen_common as c  # noqa: E402
from test_swiftgen_icons import PLAY, ROLES  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]


class BrandSwift(unittest.TestCase):
    def setUp(self):
        self.notice = (ROOT / "ASSETS-LICENSE").read_text(encoding="utf-8")
        self.files = g.generate([("glyph-39", PLAY)], ROLES, self.notice)

    def test_every_file_starts_with_the_assets_notice(self):
        full = c.license_comment(self.notice)
        for path, text in self.files.items():
            self.assertTrue(path.startswith("Sources/SymbioticBrand/Generated/"))
            self.assertTrue(text.startswith(full), path)
            self.assertIn("// Contact: symbioticaudio@proton.me", text)
            self.assertNotIn("MIT", text.split("Generated by")[1])

    def test_glyph_enum_and_role_map(self):
        glyphs = self.files["Sources/SymbioticBrand/Generated/BrandGlyph+Generated.swift"]
        roles = self.files["Sources/SymbioticBrand/Generated/BrandRoles+Generated.swift"]
        self.assertIn('    case glyph39 = "glyph-39"', glyphs)
        self.assertIn("import SymbioticIcons", glyphs)
        self.assertIn("        case .brandLogo: return .glyph39", roles)
        self.assertNotIn("transportPlay", roles)

    def test_repository_sources_carry_the_notice(self):
        """Every .swift under Sources/SymbioticBrand/ and Tests/SymbioticBrandTests/, at any depth."""
        full = c.license_comment(self.notice)
        for folder in ("Sources/SymbioticBrand", "Tests/SymbioticBrandTests"):
            self.assertTrue(sorted((ROOT / folder).rglob("*.swift")), folder)
        for path in g.stamped_sources(ROOT):
            with self.subTest(str(path.relative_to(ROOT))):
                self.assertTrue(path.read_text(encoding="utf-8").startswith(full))

    def test_assets_license_lists_the_brand_paths(self):
        for rel in ("Sources/SymbioticBrand/", "Tests/SymbioticBrandTests/",
                    "icons/glyphs.json", "icons/coverage.md"):
            with self.subTest(rel):
                self.assertIn(rel, self.notice)

    def test_mit_generated_sources_hold_no_glyph_data(self):
        for product in ("SymbioticTokens", "SymbioticIcons"):
            for path in sorted((ROOT / "Sources" / product).rglob("*")):
                if path.is_file():
                    text = path.read_text(encoding="utf-8")
                    with self.subTest(str(path.relative_to(ROOT))):
                        self.assertNotIn("glyph-", text)
                        self.assertNotIn("BrandGlyph", text)


class Restamp(unittest.TestCase):
    """Hand-written brand Swift gets its notice from ASSETS-LICENSE, never a hand copy."""

    def test_replaces_a_stale_leading_notice(self):
        text = "// old notice\n// line two\n\nimport SymbioticIcons\n/// doc\n"
        self.assertEqual(g.restamp(text, "New\n\nNotice\n"),
                         "// New\n//\n// Notice\n\nimport SymbioticIcons\n/// doc\n")

    def test_is_idempotent(self):
        once = g.restamp("// x\n\nlet a = 1\n", "A\nB\n")
        self.assertEqual(g.restamp(once, "A\nB\n"), once)

    def test_requires_a_blank_line_after_the_header(self):
        with self.assertRaises(ValueError):
            g.restamp("// header\nimport SymbioticIcons\n", "A\n")


if __name__ == "__main__":
    unittest.main()
